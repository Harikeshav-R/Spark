import { z } from "zod";
import type { UUID, ActorContext } from "../../contracts/common.js";
import { uuidSchema } from "../../contracts/common.js";
import type { ConceptNode } from "../../contracts/course.js";
import type {
  LearningService,
  StudentQuizQuestion,
  SubmitQuizAnswer,
  SubmitQuizResponse,
  ConceptQuizQuestion,
} from "../../contracts/learning.js";
import {
  getQuizResponseSchema,
  submitQuizResponseSchema,
} from "../../contracts/learning.js";
import type { AiService } from "../../contracts/ai.js";
import { generatedQuizQuestionsSchema } from "../../contracts/ai.js";
import { AppError, DomainErrorCode } from "../../contracts/errors.js";
import type { GraphRepository, LearningEvidenceService } from "../core/index.js";
import type { QuizRepositoryPort } from "./quiz-repository.js";

const strictSubmitQuizAnswerSchema = z
  .object({
    questionId: uuidSchema,
    selectedOption: z.number().int().min(0).max(3),
  })
  .strict();

const strictSubmitQuizRequestSchema = z
  .object({
    studentId: uuidSchema,
    conceptId: uuidSchema,
    answers: z.array(strictSubmitQuizAnswerSchema).min(1).max(5),
  })
  .strict();

export interface QuizServiceDependencies {
  courseId: UUID;
  topology: Pick<GraphRepository, "getTopology">;
  repository: QuizRepositoryPort;
  ai: Pick<AiService, "generateQuizQuestions">;
  evidence: Pick<LearningEvidenceService, "applyQuizAttempt">;
}

export class QuizService implements Pick<LearningService, "getQuiz" | "submitQuiz"> {
  constructor(private readonly deps: QuizServiceDependencies) {}

  async getQuiz(actor: ActorContext, conceptId: UUID): Promise<StudentQuizQuestion[]> {
    const { targetConcept } = await this.authorizeStudentAndConcept(
      actor,
      conceptId
    );

    let stored = await this.deps.repository.getQuestions(targetConcept.id);

    if (stored.length === 0) {
      const generated = await this.deps.ai.generateQuizQuestions(targetConcept);
      const validatedGenerated = generatedQuizQuestionsSchema.safeParse({
        questions: generated,
      });

      if (!validatedGenerated.success) {
        throw new AppError({
          code: DomainErrorCode.BAD_GATEWAY,
          statusCode: 502,
          message: "Invalid quiz questions generated by AI",
          cause: validatedGenerated.error,
        });
      }

      await this.deps.repository.insertQuestions(targetConcept.id, validatedGenerated.data.questions);
      stored = await this.deps.repository.getQuestions(targetConcept.id);
    }

    if (stored.length !== 5) {
      throw new AppError({
        code: DomainErrorCode.INTERNAL_SERVER_ERROR,
        statusCode: 500,
        message: "Quiz question bank is incomplete",
      });
    }

    const uniqueIds = new Set(stored.map((q) => q.id));
    if (uniqueIds.size !== 5) {
      throw new AppError({
        code: DomainErrorCode.INTERNAL_SERVER_ERROR,
        statusCode: 500,
        message: "Quiz question bank is incomplete",
      });
    }

    const publicQuestions: StudentQuizQuestion[] = stored.map((q) => ({
      id: q.id,
      question: q.question,
      options: [q.optionA, q.optionB, q.optionC, q.optionD],
      questionOrder: q.questionOrder,
    }));

    const validatedResponse = getQuizResponseSchema.safeParse({
      conceptId: targetConcept.id,
      questions: publicQuestions,
    });

    if (!validatedResponse.success) {
      throw new AppError({
        code: DomainErrorCode.INTERNAL_SERVER_ERROR,
        statusCode: 500,
        message: "Quiz question bank is incomplete",
        cause: validatedResponse.error,
      });
    }

    return validatedResponse.data.questions;
  }

  async submitQuiz(
    actor: ActorContext,
    studentId: UUID,
    conceptId: UUID,
    answers: SubmitQuizAnswer[]
  ): Promise<SubmitQuizResponse> {
    const parsedRequest = strictSubmitQuizRequestSchema.safeParse({
      studentId,
      conceptId,
      answers,
    });

    if (!parsedRequest.success) {
      throw new AppError({
        code: DomainErrorCode.VALIDATION_ERROR,
        statusCode: 400,
        message: "Invalid quiz submission",
        cause: parsedRequest.error,
      });
    }

    const submittedQuestionIds = parsedRequest.data.answers.map((a) => a.questionId);
    const uniqueSubmittedIds = new Set(submittedQuestionIds);
    if (uniqueSubmittedIds.size !== submittedQuestionIds.length) {
      throw new AppError({
        code: DomainErrorCode.VALIDATION_ERROR,
        statusCode: 400,
        message: "Invalid quiz submission",
      });
    }

    const { courseId, targetConcept, resolvedStudentId } =
      await this.authorizeStudentAndConcept(actor, conceptId, studentId);

    const storedQuestions = await this.deps.repository.getQuestionsByIds(
      targetConcept.id,
      submittedQuestionIds
    );

    if (storedQuestions.length !== submittedQuestionIds.length) {
      throw new AppError({
        code: DomainErrorCode.VALIDATION_ERROR,
        statusCode: 400,
        message: "Invalid quiz submission",
      });
    }

    const storedMap = new Map<string, ConceptQuizQuestion>();
    for (const q of storedQuestions) {
      if (q.conceptId !== targetConcept.id) {
        throw new AppError({
          code: DomainErrorCode.VALIDATION_ERROR,
          statusCode: 400,
          message: "Invalid quiz submission",
        });
      }
      storedMap.set(q.id, q);
    }

    let correctCount = 0;
    const gradedAnswers: {
      questionId: UUID;
      selectedOption: number;
      correct: boolean;
    }[] = [];

    for (const ans of parsedRequest.data.answers) {
      const stored = storedMap.get(ans.questionId);
      if (!stored) {
        throw new AppError({
          code: DomainErrorCode.VALIDATION_ERROR,
          statusCode: 400,
          message: "Invalid quiz submission",
        });
      }

      const isCorrect = ans.selectedOption === stored.correctAnswer;
      if (isCorrect) {
        correctCount++;
      }

      gradedAnswers.push({
        questionId: ans.questionId,
        selectedOption: ans.selectedOption,
        correct: isCorrect,
      });
    }

    const score = correctCount / 5;

    const attempt = await this.deps.repository.insertAttempt({
      studentId: resolvedStudentId,
      conceptId: targetConcept.id,
      score,
      correctCount,
      totalQuestions: 5,
      submittedAnswers: gradedAnswers,
    });

    const evidenceResult = await this.deps.evidence.applyQuizAttempt(
      actor,
      courseId,
      attempt.id
    );

    const response: SubmitQuizResponse = {
      attemptId: attempt.id,
      score,
      correctCount,
      totalQuestions: 5,
      newConfidence: evidenceResult.confidence,
      newBand: evidenceResult.band,
    };
    const validatedResponse = submitQuizResponseSchema.safeParse(response);
    if (!validatedResponse.success) {
      throw new AppError({
        code: DomainErrorCode.INTERNAL_SERVER_ERROR,
        statusCode: 500,
        message: "Invalid quiz submission response",
        cause: validatedResponse.error,
      });
    }

    return validatedResponse.data;
  }

  private async authorizeStudentAndConcept(
    actor: ActorContext,
    conceptId: UUID,
    positionalStudentId?: UUID
  ): Promise<{
    courseId: UUID;
    targetConcept: ConceptNode;
    resolvedStudentId: UUID;
  }> {
    const courseIdParsed = uuidSchema.safeParse(this.deps.courseId);
    const conceptIdParsed = uuidSchema.safeParse(conceptId);

    if (!courseIdParsed.success || !conceptIdParsed.success) {
      throw new AppError({
        code: DomainErrorCode.VALIDATION_ERROR,
        statusCode: 400,
        message: "Invalid quiz identifier",
        cause: !courseIdParsed.success ? courseIdParsed.error : conceptIdParsed.error,
      });
    }

    const courseId = courseIdParsed.data;
    const targetId = conceptIdParsed.data;

    if (actor.role !== "student") {
      throw new AppError({
        code: DomainErrorCode.FORBIDDEN,
        statusCode: 403,
        message: "Quiz access requires the enrolled student",
      });
    }

    const enrollment = actor.enrolledCourses?.find((e) => e.courseId === courseId);
    if (!enrollment) {
      throw new AppError({
        code: DomainErrorCode.FORBIDDEN,
        statusCode: 403,
        message: "Quiz access requires the enrolled student",
      });
    }

    const resolvedStudentId = enrollment.studentId;

    if (positionalStudentId !== undefined && positionalStudentId !== resolvedStudentId) {
      throw new AppError({
        code: DomainErrorCode.FORBIDDEN,
        statusCode: 403,
        message: "Quiz access requires the enrolled student",
      });
    }

    const topology = await this.deps.topology.getTopology(actor, courseId);
    const targetConcept = topology.nodes.find((n) => n.id === targetId);

    if (!targetConcept || targetConcept.courseId !== courseId) {
      throw new AppError({
        code: DomainErrorCode.NOT_FOUND,
        statusCode: 404,
        message: "Concept not found in authorized course",
      });
    }

    return {
      courseId,
      targetConcept,
      resolvedStudentId,
    };
  }
}
